it('does not publish a candidate when the WAL transition fails with SQLITE_BUSY', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cg-wal-busy-candidate-'));
  const { DatabaseSync } = require('node:sqlite');
  const coordinator = new PortableCoordinator(root), writer = coordinator.acquireWriter();
  const baseline = coordinator.reserveInitialActive();
  const initial = DatabaseConnection.initialize(baseline); initial.close();
  coordinator.installInitialActive();
  const candidate = coordinator.beginInitialCandidate();
  const replacement = DatabaseConnection.initialize(candidate.path); replacement.close();
  const original = DatabaseSync.prototype.exec;
  const spy = vi.spyOn(DatabaseSync.prototype, 'exec').mockImplementation(function (this: unknown, sql: string) {
    if (/^\s*PRAGMA\s+journal_mode\s*=\s*WAL\s*;?\s*$/i.test(sql))
      throw Object.assign(new Error('database is locked'), { errcode: 5 });
    return original.call(this, sql);
  });
  try {
    await expect(coordinator.publishInitialCandidate(candidate)).rejects.toThrow(/locked/);
    expect(coordinator.snapshot()).toEqual({ mode: 'idle', revision: 0 });
    expect(fs.existsSync(candidate.path)).toBe(true);
  } finally {
    spy.mockRestore(); writer.release(); fs.rmSync(root, { recursive: true, force: true });
  }
});
