import { createHash } from 'node:crypto';
import { PortableCoordinator } from '../src/sync/portable/protocol';
import { DatabaseConnection } from '../src/db';

it('retains a usable DELETE database when SQLite leaves WAL mode unchanged', async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cg-wal-fallback-'));
  const { DatabaseSync } = require('node:sqlite');
  const original = DatabaseSync.prototype.exec;
  const spy = vi.spyOn(DatabaseSync.prototype, 'exec').mockImplementation(function (this: unknown, sql: string) {
    if (/^\s*PRAGMA\s+journal_mode\s*=\s*WAL\s*;?\s*$/i.test(sql)) {
      return; // SQLite can also leave the mode unchanged without throwing.
    }
    return original.call(this, sql);
  });
  const coordinator = new PortableCoordinator(root);
  const writer = coordinator.acquireWriter();
  try {
    const baseline = coordinator.reserveInitialActive();
    const initial = DatabaseConnection.initialize(baseline); initial.close();
    coordinator.installInitialActive();
    const candidate = coordinator.beginInitialCandidate();
    const replacement = DatabaseConnection.initialize(candidate.path); replacement.close();
    await coordinator.publishInitialCandidate(candidate);
    const opened = DatabaseConnection.open(coordinator.active);
    try {
      expect(String(opened.getDb().pragma('journal_mode', { simple: true })).toLowerCase()).toBe('delete');
      expect(opened.getDb().prepare('PRAGMA quick_check').get().quick_check).toBe('ok');
    } finally { opened.close(); }
  } finally {
    spy.mockRestore(); writer.release();
    fs.rmSync(root, { recursive: true, force: true });
  }
});

it('does not mistake a legacy DELETE database with a live reader for an unsupported WAL filesystem', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cg-legacy-delete-reader-'));
  const file = path.join(root, 'legacy.db');
  const { DatabaseSync } = require('node:sqlite');
  // Actual database generated by the unreleased 87bb4846-equivalent tree,
  // not a current database whose journal mode was altered by this test.
  const bytes = gunzipSync(fs.readFileSync(path.join(__dirname, 'fixtures/unreleased-87bb4846/codegraph.db.gz')));
  expect(createHash('sha256').update(bytes).digest('hex')).toBe('61b890a52bdd2f99e440278b55b9dd1f9e976be5d95d575e55458a156ac1a8ab');
  fs.writeFileSync(file, bytes);
  const reader = new DatabaseSync(file, { readOnly: true });
  reader.exec('BEGIN'); reader.prepare('SELECT count(*) FROM sqlite_master').get();
  try {
    expect(() => DatabaseConnection.open(file)).toThrow(/locked|busy/i);
    expect(reader.prepare('PRAGMA journal_mode').get().journal_mode).toBe('delete');
  } finally { reader.exec('COMMIT'); reader.close(); }
  const reopened = DatabaseConnection.open(file);
  try {
    expect(reopened.getDb().pragma('journal_mode', { simple: true })).toBe('wal');
    expect(reopened.getDb().prepare("SELECT count(*) AS n FROM nodes WHERE name='published_value'").get().n).toBeGreaterThan(0);
  }
  finally { reopened.close(); fs.rmSync(root, { recursive: true, force: true }); }
}, 15000);

it.each([5, 6, 8, 10, 14, 520, 776, 1288, 1294, 4618, 4874, 5130, 5386])('does not silently degrade on SQLite failure %i', async errcode => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cg-wal-error-'));
  const file = path.join(root, 'db.sqlite');
  const { DatabaseSync } = require('node:sqlite');
  const setup = new DatabaseSync(file); setup.exec('CREATE TABLE test(x)'); setup.close();
  const original = DatabaseSync.prototype.exec;
  const spy = vi.spyOn(DatabaseSync.prototype, 'exec').mockImplementation(function (this: unknown, sql: string) {
    if (/^\s*PRAGMA\s+journal_mode\s*=\s*WAL\s*;?\s*$/i.test(sql))
      throw Object.assign(new Error('injected SQLite failure'), { errcode });
    return original.call(this, sql);
  });
  try { expect(() => DatabaseConnection.open(file)).toThrow('injected SQLite failure'); }
  finally { spy.mockRestore(); fs.rmSync(root, { recursive: true, force: true }); }
});

